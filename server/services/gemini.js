const { z } = require('zod');
const config = require('../config');

const parsedScheduleSchema = z.object({
  name: z.string().min(1),
  dosage: z.string().min(1),
  instructions: z.string().min(1),
  frequency: z.enum(['ONCE_DAILY', 'TWICE_DAILY', 'THRICE_DAILY', 'AS_NEEDED', 'CUSTOM']),
  timeSlots: z.array(z.string().regex(/^([01]\d|2[0-3]):([0-5]\d)$/)),
  durationDays: z.number().int().positive().optional(),
  disclaimer: z.string()
});

async function parsePrescriptionText(prescriptionText) {
  if (!config.geminiApiKey) {
    throw new Error('Gemini API key is not configured');
  }

  const systemPrompt = `You are a medical assistant helping structure medication schedules for an elderly patient.
Extract medication details from the user's prescription description.
Respond ONLY with a valid JSON object matching this schema:
{
  "name": "Medication name e.g. Metformin",
  "dosage": "Dosage amount e.g. 500 mg or 1 tablet",
  "instructions": "Simple plain-language instruction for a senior citizen e.g. Take after breakfast with water",
  "frequency": "ONCE_DAILY" | "TWICE_DAILY" | "THRICE_DAILY" | "AS_NEEDED" | "CUSTOM",
  "timeSlots": ["HH:MM in 24hr format, e.g. ['08:30', '20:30']"],
  "durationDays": 14,
  "disclaimer": "AI-suggested schedule. Always confirm with the prescribing healthcare provider."
}
Do not include markdown backticks like \`\`\`json. Output pure JSON only.`;

  const url = `https://generativelanguage.googleapis.com/v1beta/models/${config.geminiModel}:generateContent?key=${config.geminiApiKey}`;

  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [
        {
          parts: [
            { text: `${systemPrompt}\n\nPrescription input: "${prescriptionText}"` }
          ]
        }
      ]
    }),
    signal: AbortSignal.timeout(12000)
  });

  if (!response.ok) {
    const errorBody = await response.text();
    throw new Error(`Gemini API returned error: ${response.status} - ${errorBody}`);
  }

  const data = await response.json();
  const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text;

  if (!rawText) {
    throw new Error('No response generated by Gemini');
  }

  // Strip code fences if model returned them
  const cleanedText = rawText.replace(/```json/g, '').replace(/```/g, '').trim();
  const parsedJson = JSON.parse(cleanedText);

  // Validate through Zod
  const validated = parsedScheduleSchema.parse(parsedJson);
  return validated;
}

module.exports = {
  parsePrescriptionText,
  parsedScheduleSchema
};

